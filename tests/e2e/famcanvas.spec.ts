test("pricing and responsive canvas", async ({ page }) => {
  await page.goto("/pricing");
  await expect(page.getByRole("heading", { name: "Family Premium", exact: true })).toBeVisible();
  await expect(page.locator(".premium-price .price")).toContainText("6.99");
  await page.getByRole("button", { name: "Yearly Save 30%" }).click();
  await expect(page.locator(".premium-price .price")).toContainText("59");
  await page.getByRole("button", { name: "Make room for more" }).click();
  await expect(page.getByRole("dialog")).toContainText("Sign in with a secure email link");
  await page.getByRole("button", { name: "Close dialog" }).click();
  await page.goto("/"); await page.screenshot({ path: "test-results/canvas-desktop.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole("heading", { name: "Our family canvas" })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  await page.screenshot({ path: "test-results/canvas-mobile.png", fullPage: true });
});
test("API guards reject unauthorized billing, webhooks, cron and invalid AI input", async ({ request }) => {
  expect((await request.get("/api/cron/evening-reminder")).status()).toBe(401);
  expect((await request.post("/api/webhooks/stripe", { data: {} })).status()).toBe(400);
  expect((await request.post("/api/generate-story", { data: { start: "bad", end: "bad" } })).status()).toBe(400);
  expect((await request.post("/api/generate-story", { headers: { origin: "https://evil.example" }, data: {} })).status()).toBe(403);
  expect((await request.post("/api/stripe/checkout", { data: { interval: "forever" } })).status()).toBe(400);
  expect((await request.post("/api/stripe/portal", { data: {} })).status()).toBe(503);
});
