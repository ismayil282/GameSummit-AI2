import { test, expect } from "@playwright/test";
test("canvas, notes, dragging, albums and demo persistence", async ({ page }) => {
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message));
  await page.goto("/");
  await expect(page.getByRole("heading", { name: "Our family canvas" })).toBeVisible();
  await expect(page.locator(".memory-card")).toHaveCount(7);
  await page.getByTitle("Add a note", { exact: true }).click();
  await page.getByPlaceholder("A little win, a funny moment, or just ‘I love you’…").fill("We made pancakes together this morning!");
  await page.getByRole("button", { name: "Add to our canvas" }).click();
  await expect(page.locator(".memory-card")).toHaveCount(8);
  await expect(page.getByText("We made pancakes together this morning!", { exact: true })).toBeVisible();
  const note = page.locator(".memory-card.note").first();
  const before = await note.evaluate(el => (el as HTMLElement).style.left);
  const box = (await note.boundingBox())!;
  await page.mouse.move(box.x + 55, box.y + 50); await page.mouse.down(); await page.mouse.move(box.x + 95, box.y + 80, { steps: 8 }); await page.mouse.up();
  await expect.poll(() => note.evaluate(el => (el as HTMLElement).style.left)).not.toBe(before);
  await page.reload(); await expect(page.locator(".memory-card")).toHaveCount(8);
  await page.getByRole("button", { name: "Create a storybook", exact: true }).click();
  await expect(page.getByRole("dialog")).toBeVisible();
  await expect(page.getByRole("heading", { name: "The magic in our everyday" })).toBeVisible();
  await page.getByRole("button", { name: "Close dialog" }).click();
  await page.getByRole("link", { name: "Memory albums" }).click();
  await expect(page.getByRole("heading", { name: "Our memory albums" })).toBeVisible();
  await expect(page.locator(".album-card")).toHaveCount(1);
  await page.screenshot({ path: "test-results/albums.png", fullPage: true });
  expect(errors).toEqual([]);
});
